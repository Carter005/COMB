-- Clean new story records when a test target is replaced or cleared.
create or replace function public.o8_cleanup_story_target()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  if old.token_address is not null and lower(old.token_address) is distinct from lower(new.token_address) then
    delete from public.o8_story_milestones where target_address=lower(old.token_address);
    delete from public.o8_story_state where target_address=lower(old.token_address);
  end if;
  return new;
end $$;
drop trigger if exists o8_cleanup_story_target_trigger on public.o8_token_targets;
create trigger o8_cleanup_story_target_trigger after update of token_address on public.o8_token_targets
for each row execute function public.o8_cleanup_story_target();

