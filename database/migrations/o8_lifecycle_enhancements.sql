  if coalesce(new.graduated,false) and new.pool_address is not null then
    observed:=nullif(new.metadata->>'observedBlock','')::bigint;
    perform public.o8_emit_story_milestone(target,'graduated_pool_verified','POST_GRAD','graduated_pool_verified','GRADUATED POOL VERIFIED',
      'AUDITOR verified the graduated pool address retained from the Pons and Uniswap V3 route. This is not a liquidity-quality claim.',
      'ARM-05',observed,jsonb_build_object('poolAddress',lower(new.pool_address),'graduationProgressPct',new.graduation_progress,'status',new.status));
  end if;
  return new;
end $$;

