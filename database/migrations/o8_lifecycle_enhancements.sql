create or replace function public.o8_evaluate_story_state()
returns jsonb language plpgsql security definer set search_path=public as $$
declare
  target_row public.o8_token_targets%rowtype;
  story public.o8_story_state%rowtype;
  observer public.o8_system_bindings%rowtype;
  chain public.o8_sources%rowtype;
  observer_poll timestamptz;
  healthy boolean;
  reference_time timestamptz;
  silent_seconds integer;
begin
  select * into target_row from public.o8_token_targets where id='o8';
  if target_row.token_address is null then return jsonb_build_object('evaluated',false,'reason','no target'); end if;
  insert into public.o8_story_state(target_address) values(lower(target_row.token_address)) on conflict do nothing;
  select * into story from public.o8_story_state where target_address=lower(target_row.token_address) for update;
  select * into observer from public.o8_system_bindings where id='railway-observer';
  select * into chain from public.o8_sources where id='robinhood-mainnet';
  observer_poll:=nullif(observer.details->>'lastPollAt','')::timestamptz;
  healthy:=observer.status='CONNECTED' and observer_poll>now()-interval '45 seconds'
    and chain.status='CONNECTED' and chain.last_checked_at>now()-interval '45 seconds';

  if not healthy then
    if story.observer_health is distinct from 'DEGRADED' then
      story.gap_sequence:=story.gap_sequence+1;
      perform public.o8_emit_story_milestone(lower(target_row.token_address),'observer_gap_'||story.gap_sequence,'INFRA','observer_gap','OBSERVER GAP',
        'WATCHER detected an observation gap. Target silence is not inferred while Railway or chain freshness is degraded.',
        'ARM-01',null,jsonb_build_object('observerStatus',observer.status,'lastPollAt',observer_poll,'chainStatus',chain.status,'chainLastCheckedAt',chain.last_checked_at));
    end if;
    update public.o8_story_state set observer_health='DEGRADED',gap_sequence=story.gap_sequence,updated_at=now() where target_address=lower(target_row.token_address);
    return jsonb_build_object('evaluated',true,'observerHealthy',false,'silenceInferred',false);
  end if;

  if story.observer_health='DEGRADED' then
    perform public.o8_emit_story_milestone(lower(target_row.token_address),'observer_recovered_'||story.gap_sequence,'INFRA','observer_recovered','OBSERVATION RESTORED',
      'WATCHER verified that Railway polling and Robinhood Chain freshness recovered. Silence evaluation may resume.',
      'ARM-01',null,jsonb_build_object('lastPollAt',observer_poll,'chainLastCheckedAt',chain.last_checked_at));
  end if;

  reference_time:=coalesce(story.last_activity_at,story.created_at);
  silent_seconds:=greatest(0,extract(epoch from now()-reference_time)::integer);
  if silent_seconds>=900 and story.silence_state<>'SILENT' then
    story.silence_sequence:=story.silence_sequence+1;
    perform public.o8_emit_story_milestone(lower(target_row.token_address),'silence_15m_'||story.silence_sequence,'SILENCE','target_silence','VERIFIED SILENCE',
      'WATCHER observed no target-scoped transactions, transfers, or pool events for at least 15 minutes while Railway and chain freshness remained healthy.',
      'ARM-01',story.last_activity_block,jsonb_build_object('silenceSeconds',silent_seconds,'lastActivityAt',story.last_activity_at,'observerHealthy',true));
    update public.o8_story_state set observer_health='HEALTHY',silence_state='SILENT',silence_sequence=story.silence_sequence,updated_at=now()
      where target_address=lower(target_row.token_address);
  else
    update public.o8_story_state set observer_health='HEALTHY',updated_at=now() where target_address=lower(target_row.token_address);
  end if;
  return jsonb_build_object('evaluated',true,'observerHealthy',true,'silenceState',case when silent_seconds>=900 then 'SILENT' else story.silence_state end,'silenceSeconds',silent_seconds);
end $$;

create or replace function public.o8_tick()
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  specimen public.o8_specimen%rowtype;
  next_tick bigint;
  story_result jsonb;
begin
  story_result:=public.o8_evaluate_story_state();
  select * into specimen from public.o8_specimen where id='o8' for update;
  if specimen.updated_at>now()-interval '12 seconds' then
    return jsonb_build_object('advanced',false,'heartbeat',specimen.tick_count,'story',story_result);
  end if;
  next_tick:=specimen.tick_count+1;
  update public.o8_specimen set
    tick_count=next_tick,
    next_scan_at=case when next_scan_at<=now() then now()+interval '60 seconds' else next_scan_at end,
    next_sync_at=now()+interval '5 minutes',
    updated_at=now()
  where id='o8';
  return jsonb_build_object('advanced',true,'heartbeat',next_tick,'story',story_result);
end $$;

