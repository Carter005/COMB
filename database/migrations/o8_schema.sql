create table if not exists public.o8_specimen (
  id text primary key default 'o8',
  status text not null default 'OBSERVING',
  depth_m integer not null default 3842,
  pressure_bar numeric(6,1) not null default 382.7,
  coherence numeric(5,1) not null default 88.4,
  identity_drift numeric(5,1) not null default 1.7,
  signal_strength numeric(4,2) not null default 0.72,
  echoes_captured integer not null default 2914,
  unknown_sources integer not null default 2,
  next_scan_at timestamptz not null default now() + interval '60 seconds',
  next_sync_at timestamptz not null default now() + interval '5 minutes',
  tick_count bigint not null default 0,
  updated_at timestamptz not null default now()
);

create table if not exists public.o8_arms (
  id smallint primary key check (id between 1 and 8),
  role text not null,
  state text not null,
  node_name text not null,
  latency_ms integer not null,
  packet_loss numeric(5,2) not null default 0,
  route_confidence numeric(4,2) not null default 0.8,
  last_event_at timestamptz not null default now()
);

create table if not exists public.o8_sources (
  id text primary key,
  label text not null,
  kind text not null,
  truth text not null check (truth in ('CONNECTED', 'SYSTEM', 'SYNTHETIC')),
  status text not null,
  latency_ms integer,
  last_checked_at timestamptz not null default now(),
  payload jsonb not null default '{}'::jsonb
);

create table if not exists public.o8_fragments (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  status text not null check (status in ('preserved', 'disputed', 'compressed', 'lost')),
  summary text not null,
  source_arm smallint references public.o8_arms(id),
  confidence numeric(4,2) not null default 0.5
);

create table if not exists public.o8_events (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  type text not null,
  source text not null,
  truth text not null check (truth in ('CONNECTED', 'SYSTEM', 'SYNTHETIC', 'O8')),
  text text not null,
  metadata jsonb not null default '{}'::jsonb
);

create index if not exists o8_events_created_at_idx on public.o8_events(created_at desc);
create index if not exists o8_fragments_created_at_idx on public.o8_fragments(created_at desc);

