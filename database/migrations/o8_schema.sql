create or replace function public.o8_tick()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  specimen public.o8_specimen%rowtype;
  selected_arm smallint;
  next_latency integer;
  event_id bigint;
  event_text text;
  event_type text;
  event_source text;
  event_truth text;
begin
  select * into specimen from public.o8_specimen where id = 'o8' for update;

  if specimen.updated_at > now() - interval '12 seconds' then
    return jsonb_build_object('advanced', false, 'tick', specimen.tick_count);
  end if;

  selected_arm := ((specimen.tick_count % 8) + 1)::smallint;
  next_latency := greatest(34, least(960, (select latency_ms from public.o8_arms where id = selected_arm) + floor(random() * 43 - 20)::integer));

  update public.o8_arms
    set latency_ms = next_latency,
        packet_loss = greatest(0, least(8, packet_loss + (random() * 0.8 - 0.35))),
        route_confidence = greatest(0.18, least(0.98, route_confidence + (random() * 0.08 - 0.035))),
        last_event_at = now()
  where id = selected_arm;

  if specimen.tick_count > 0 and specimen.tick_count % 20 = 0 then
    update public.o8_specimen
      set coherence = greatest(78, least(96, coherence + (random() * 2.4 - 0.8))),
          identity_drift = greatest(0.3, least(8, identity_drift + (random() * 0.5 - 0.2))),
          next_sync_at = now() + interval '5 minutes'
    where id = 'o8';
    insert into public.o8_fragments(status, summary, source_arm, confidence)
      values ('preserved', 'synchronization retained a stable pressure sequence', selected_arm, 0.82)
      returning id into event_id;
    event_type := 'memory_sync'; event_source := 'ARM-08'; event_truth := 'SYSTEM';
    event_text := 'synchronization complete. one new fragment was retained; coherence recalculated.';
  elsif specimen.tick_count % 7 = 0 then
    event_type := 'route_changed'; event_source := 'ARM-' || lpad(selected_arm::text, 2, '0'); event_truth := 'SYSTEM';
    event_text := 'route weighting changed after latency reached ' || next_latency || 'ms. the fallback remains available.';
  elsif specimen.tick_count % 5 = 0 then
    event_type := 'observation'; event_source := 'O8'; event_truth := 'SYNTHETIC';
    event_text := 'the arms compared the same signal and produced two different distances.';
  else
    event_type := 'source_reading'; event_source := 'ARM-' || lpad(selected_arm::text, 2, '0'); event_truth := 'SYSTEM';
    event_text := 'node sample completed at ' || next_latency || 'ms. no decisive anomaly established.';
  end if;

  insert into public.o8_events(type, source, truth, text, metadata)
    values (event_type, event_source, event_truth, event_text, jsonb_build_object('armId', selected_arm, 'latencyMs', next_latency))
    returning id into event_id;

  update public.o8_specimen
    set tick_count = tick_count + 1,
        echoes_captured = echoes_captured + case when random() > 0.35 then 1 else 0 end,
        signal_strength = greatest(0.22, least(0.94, signal_strength + (random() * 0.06 - 0.025))),
        pressure_bar = greatest(378, least(388, pressure_bar + (random() * 0.12 - 0.055))),
        next_scan_at = case when next_scan_at <= now() then now() + interval '60 seconds' else next_scan_at end,
        updated_at = now()
  where id = 'o8';

  delete from public.o8_events where id in (select id from public.o8_events order by id desc offset 500);

  return jsonb_build_object('advanced', true, 'eventId', event_id, 'armId', selected_arm);
end;
$$;

