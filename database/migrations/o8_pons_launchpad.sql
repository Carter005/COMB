create table if not exists public.o8_token_targets (
  id text primary key,
  platform text not null default 'PONS',
  symbol text not null default 'O8',
  token_name text,
  token_address text unique,
  status text not null default 'AWAITING_LAUNCH',
  factory_address text not null,
  locker_address text,
  deployer_address text,
  pool_address text,
  pair_token_address text,
  launch_tx_hash text,
  launch_block bigint,
  launched_at timestamptz,
  initial_buy_wei numeric(78,0),
  total_supply numeric(78,0),
  dex_id bigint,
  launch_config_id bigint,
  position_id numeric(78,0),
  restrictions_end_block bigint,
  pool_fee integer,
  graduation_progress numeric(7,3),
  paired_principal_wei numeric(78,0),
  graduation_threshold_wei numeric(78,0),
  graduated boolean not null default false,
  price_usd numeric,
  market_cap_usd numeric,
  metadata jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.o8_token_lifecycle_snapshots (
  id bigint generated by default as identity primary key,
  target_id text not null references public.o8_token_targets(id) on delete cascade,
  observed_at timestamptz not null default now(),
  status text not null,
  graduation_progress numeric(7,3),
  paired_principal_wei numeric(78,0),
  graduation_threshold_wei numeric(78,0),
  pool_address text,
  pool_liquidity numeric(78,0),
  pool_sqrt_price_x96 numeric(78,0),
  observed_block bigint,
  payload jsonb not null default '{}'::jsonb
);

create index if not exists o8_token_lifecycle_target_idx
  on public.o8_token_lifecycle_snapshots(target_id, observed_at desc);

alter table public.o8_token_targets enable row level security;
alter table public.o8_token_lifecycle_snapshots enable row level security;

drop policy if exists "o8 public read token targets" on public.o8_token_targets;
