create or replace function public.o8_register_pons_token(p_token_address text, p_launch_tx_hash text default null)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
begin
  if p_token_address !~* '^0x[0-9a-f]{40}$' then
    raise exception 'invalid token address';
  end if;
  if p_launch_tx_hash is not null and p_launch_tx_hash !~* '^0x[0-9a-f]{64}$' then
    raise exception 'invalid launch transaction hash';
  end if;

  update public.o8_token_targets
  set token_address = lower(p_token_address),
      launch_tx_hash = coalesce(lower(p_launch_tx_hash), launch_tx_hash),
      status = 'VERIFYING',
      updated_at = now()
  where id = 'o8';

  update public.o8_system_bindings
  set status = 'VERIFYING',
      details = details || jsonb_build_object('contractAddress', lower(p_token_address), 'launchpad', 'PONS'),
      updated_at = now()
  where id = 'o8-token';

  return jsonb_build_object('registered', true, 'tokenAddress', lower(p_token_address), 'status', 'VERIFYING');
end;
$$;

create or replace function public.o8_ingest_pons_launchpad(p_snapshot jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  platform jsonb := p_snapshot->'platform';
  target jsonb := p_snapshot->'target';
  previous_status text;
  previous_progress numeric;
  previous_binding_status text;
  next_status text := coalesce(target->>'status', 'AWAITING_LAUNCH');
  next_progress numeric := nullif(target->>'graduationProgressPct', '')::numeric;
  event_id bigint;
begin
  select status, graduation_progress into previous_status, previous_progress
  from public.o8_token_targets where id = 'o8' for update;
  select status into previous_binding_status from public.o8_system_bindings where id = 'pons-launchpad';

  update public.o8_sources
  set status = 'CONNECTED',
      latency_ms = nullif(platform->>'latencyMs', '')::integer,
      last_checked_at = now(),
      payload = platform
  where id = 'pons-launchpad';

  update public.o8_system_bindings
  set status = 'CONNECTED',
      details = platform,
      updated_at = now()
  where id = 'pons-launchpad';

  if previous_binding_status is distinct from 'CONNECTED' then
    insert into public.o8_events(type, source, truth, text, metadata)
    values (
      'launchpad_bound', 'O8-SYSTEM', 'CONNECTED',
      'Pons Launchpad lifecycle is bound: factory, locker, Uniswap V3 route, launch configuration, and graduation threshold were verified on Robinhood Chain.',
      jsonb_build_object('factory', platform->>'factory', 'locker', platform->>'locker', 'graduationThresholdWei', platform->>'graduationThresholdWei')
    ) returning id into event_id;
  end if;

  if target is null or coalesce(target->>'tokenAddress', '') = '' then
    update public.o8_token_targets
    set status = 'AWAITING_LAUNCH', updated_at = now()
    where id = 'o8' and token_address is null;

    update public.o8_system_bindings
    set status = 'AWAITING_LAUNCH',
        details = jsonb_build_object(
          'symbol', 'O8', 'contractAddress', null, 'launchpad', 'PONS',
          'factory', platform->>'factory', 'stage', 'AWAITING_LAUNCH'
        ),
        updated_at = now()
    where id = 'o8-token';

    return jsonb_build_object('status', 'AWAITING_LAUNCH', 'eventId', event_id);
  end if;

  update public.o8_token_targets set
    token_name = target->>'name',
    symbol = coalesce(nullif(target->>'symbol', ''), symbol),
    token_address = lower(target->>'tokenAddress'),
    status = next_status,
    deployer_address = lower(target->>'deployer'),
    pool_address = lower(target->>'pool'),
    pair_token_address = lower(target->>'pairToken'),
    launch_tx_hash = coalesce(lower(target->>'launchTxHash'), launch_tx_hash),
    launch_block = nullif(target->>'launchBlock', '')::bigint,
    launched_at = nullif(target->>'launchedAt', '')::timestamptz,
    initial_buy_wei = nullif(target->>'initialBuyWei', '')::numeric,
    total_supply = nullif(target->>'totalSupply', '')::numeric,
    dex_id = nullif(target->>'dexId', '')::bigint,
    launch_config_id = nullif(target->>'launchConfigId', '')::bigint,
    position_id = nullif(target->>'positionId', '')::numeric,
    restrictions_end_block = nullif(target->>'restrictionsEndBlock', '')::bigint,
    pool_fee = nullif(target->>'poolFee', '')::integer,
    graduation_progress = next_progress,
    paired_principal_wei = nullif(target->>'pairedPrincipalWei', '')::numeric,
    graduation_threshold_wei = nullif(target->>'graduationThresholdWei', '')::numeric,
    graduated = coalesce((target->>'graduated')::boolean, false),
    price_usd = nullif(target->>'priceUsd', '')::numeric,
    market_cap_usd = nullif(target->>'marketCapUsd', '')::numeric,
    metadata = coalesce(target->'metadata', '{}'::jsonb),
    updated_at = now()
  where id = 'o8';

  update public.o8_system_bindings
  set status = next_status,
      details = jsonb_build_object(
        'symbol', coalesce(target->>'symbol', 'O8'),
        'contractAddress', lower(target->>'tokenAddress'),
        'launchpad', 'PONS',
        'factory', platform->>'factory',
        'poolAddress', lower(target->>'pool'),
        'stage', next_status,
        'graduated', coalesce((target->>'graduated')::boolean, false),
        'graduationProgressPct', next_progress
      ),
      updated_at = now()
  where id = 'o8-token';

  if previous_status is distinct from next_status
     or floor(coalesce(previous_progress, -1) / 10) < floor(coalesce(next_progress, -1) / 10) then
    insert into public.o8_token_lifecycle_snapshots(
      target_id, status, graduation_progress, paired_principal_wei, graduation_threshold_wei,
      pool_address, pool_liquidity, pool_sqrt_price_x96, observed_block, payload
    ) values (
      'o8', next_status, next_progress,
      nullif(target->>'pairedPrincipalWei', '')::numeric,
      nullif(target->>'graduationThresholdWei', '')::numeric,
      lower(target->>'pool'), nullif(target->>'poolLiquidity', '')::numeric,
      nullif(target->>'poolSqrtPriceX96', '')::numeric,
      nullif(target->>'observedBlock', '')::bigint, target
    );
  end if;

  if previous_status in ('AWAITING_LAUNCH', 'VERIFYING') and next_status in ('CURVE_ACTIVE', 'GRADUATED') then
    insert into public.o8_events(type, source, truth, text, metadata)
    values (
      'token_launched', 'O8-SYSTEM', 'CONNECTED',
      '$O8 was verified as a Pons launch on Robinhood Chain. The token, deployer, pool, pair asset, launch transaction, and curve state are retained.',
      jsonb_build_object('tokenAddress', lower(target->>'tokenAddress'), 'poolAddress', lower(target->>'pool'), 'launchTxHash', lower(target->>'launchTxHash'), 'status', next_status)
    ) returning id into event_id;
  elsif previous_status is distinct from 'GRADUATED' and next_status = 'GRADUATED' then
    insert into public.o8_events(type, source, truth, text, metadata)
    values (
      'token_graduated', 'ARM-03', 'CONNECTED',
      'DEPTH verified that $O8 reached the Pons graduation threshold. Post-graduation Uniswap V3 pool monitoring is active.',
      jsonb_build_object('tokenAddress', lower(target->>'tokenAddress'), 'poolAddress', lower(target->>'pool'), 'graduationProgressPct', 100)
    ) returning id into event_id;
  elsif floor(coalesce(previous_progress, -1) / 10) < floor(coalesce(next_progress, -1) / 10) then
    insert into public.o8_events(type, source, truth, text, metadata)
    values (
      'graduation_progress', 'ARM-03', 'CONNECTED',
      'DEPTH measured Pons graduation progress at ' || round(next_progress, 1) || '%. This is an on-chain curve state, not a price prediction.',
      jsonb_build_object('tokenAddress', lower(target->>'tokenAddress'), 'graduationProgressPct', next_progress, 'pairedPrincipalWei', target->>'pairedPrincipalWei', 'thresholdWei', target->>'graduationThresholdWei')
    ) returning id into event_id;
  end if;

  update public.o8_arms
  set state = 'OBSERVING',
      node_name = 'PONS-' || case when next_status = 'GRADUATED' then 'V3-POOL' else 'CURVE' end,
      route_confidence = 1,
      mood = case when next_status = 'GRADUATED' then 'focused' else 'guarded' end,
      mood_reason = 'DEPTH is measuring verified Pons pool and graduation state for $O8',
      last_event_at = now()
  where id = 3;

  return jsonb_build_object('status', next_status, 'progress', next_progress, 'eventId', event_id, 'tokenAddress', lower(target->>'tokenAddress'));
end;
$$;

revoke all on function public.o8_register_pons_token(text, text) from public, anon, authenticated;
